-- 1. สร้างตาราง todos ภายใน Schema `public`
CREATE TABLE IF NOT EXISTS public.todos (
  -- id: รหัสประจำรายการ (Primary Key) เพิ่มค่าอัตโนมัติทีละ 1 (Auto-increment)
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

  -- title: ชื่อรายการงานที่ต้องทำ ห้ามเป็นค่าว่าง (NOT NULL)
  title TEXT NOT NULL,

  -- category: หมวดหมู่ของงาน เช่น ทั่วไป, การเรียน, งานส่วนตัว (ค่าเริ่มต้นคือ 'ทั่วไป')
  category TEXT NOT NULL DEFAULT 'ทั่วไป',

  -- is_complete: สถานะการทำงาน (false = ยังไม่เสร็จ, true = เสร็จแล้ว)
  is_complete BOOLEAN NOT NULL DEFAULT FALSE,

  -- image_url: เก็บ URL ของรูปภาพที่อัปโหลดไปยัง Supabase Storage (ใช้ในตอนที่ 5)
  image_url TEXT,

  -- user_id: รหัสผู้ใช้ (UUID) อ้างอิงไปยังตาราง auth.users ของระบบ Supabase Auth
  -- ON DELETE CASCADE หมายถึง หากผู้ใช้ถูกลบ งานทั้งหมดของผู้ใช้นี้จะถูกลบตามอัตโนมัติ
  user_id UUID REFERENCES auth.users(id) ON DELETE CASCADE,

  -- created_at: วันและเวลาที่สร้างรายการ (เก็บพร้อม Time Zone โดยใช้เวลาปัจจุบันอัตโนมัติ)
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 2. เพิ่มข้อมูลตัวอย่าง 3 รายการสำหรับทดสอบในตอนที่ 2 และตอนที่ 3
INSERT INTO public.todos (title, category, is_complete)
VALUES
  ('สร้างโปรเจกต์ Supabase และคัดลอก Publishable Key', 'การเรียน', true),
  ('ทดสอบดึงข้อมูลด้วยคำสั่ง select() ใน JavaScript', 'การเรียน', false),
  ('เปิดใช้งาน Row Level Security (RLS) ในตอนที่ 4', 'ความปลอดภัย', false);

-- 3. ปิด RLS ชั่วคราว (เฉพาะตอนทดสอบ CRUD พื้นฐานในตอนที่ 3 เท่านั้น)
-- หมายเหตุ: ในตอนที่ 4 จะรันไฟล์ 02_step4_enable_rls.sql เพื่อเปิด RLS และตั้งกฎความปลอดภัย
ALTER TABLE public.todos DISABLE ROW LEVEL SECURITY;

-- 4. แสดงผลข้อมูลทั้งหมดในแท็บ Results เพื่อตรวจสอบความเรียบร้อย
SELECT * FROM public.todos ORDER BY created_at DESC;
